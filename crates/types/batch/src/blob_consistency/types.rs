use halo2curves_axiom::bls12_381::{
    Fq as Bls12_381_Fq, G1Affine as Bls12_381_G1, G2Affine as Bls12_381_G2,
};
use openvm_algebra_guest::IntMod;
use openvm_ecc_guest::weierstrass::WeierstrassPoint;
use openvm_pairing::bls12_381::{Fp, Fp2, G1Affine, G2Affine};

/// Helper trait that provides functionality to convert the given type from native to the desired intrinsic type
pub trait ToIntrinsic {
    /// The desired intrinsic type
    type IntrinsicType;

    /// Convert the given type from native to the desired intrinsic type
    fn to_intrinsic(&self) -> Self::IntrinsicType;
}

impl ToIntrinsic for Bls12_381_Fq {
    type IntrinsicType = Fp;

    fn to_intrinsic(&self) -> Self::IntrinsicType {
        let bytes = self.to_bytes();
        Fp::from_le_bytes_unchecked(&bytes)
    }
}

impl ToIntrinsic for Bls12_381_G1 {
    type IntrinsicType = G1Affine;

    fn to_intrinsic(&self) -> Self::IntrinsicType {
        // SAFETY: callers must pass a point that is on the curve and, wherever the result is used
        // as a group element, not the identity and in the G1 subgroup. Callers:
        // - `build_point` converts *before* its subgroup check, only to run `is_in_g1_subgroup`,
        //   and returns the point only if that check passes. Its point comes from halo2curves
        //   `from_xy`, so it is on the curve.
        // - `builder::v7` converts `build_point` outputs for `verify_kzg_proof`, which rejects the
        //   identity in `from_xy_nonidentity`.
        // - Tests convert points decoded by the checked `from_compressed_be`, and one on-curve point
        //   outside the subgroup, only to check that `is_in_g1_subgroup` rejects it.
        // halo2curves encodes the identity as `(0, 1)`, not OpenVM's `(0, 0)`, so converting
        // `G1Affine::identity()` would yield an invalid point. `build_point` cannot produce it:
        // `from_xy` rejects `(0, 1)` as off-curve and keeps `(0, 0)`, which converts to OpenVM's
        // identity.
        unsafe { G1Affine::from_xy_unchecked(self.x.to_intrinsic(), self.y.to_intrinsic()) }
    }
}

impl ToIntrinsic for Bls12_381_G2 {
    type IntrinsicType = G2Affine;

    fn to_intrinsic(&self) -> Self::IntrinsicType {
        // SAFETY: callers must pass a point that is on the curve, not the identity (halo2curves
        // encodes it as `(0, 1)`, not OpenVM's `(0, 0)`) and in the G2 subgroup. The only callers
        // are tests, which pass the G2 generator and the KZG setup point decoded by the checked
        // `from_compressed_be`. The guest's G2 constants are generated by `build.rs`, not through
        // this impl.
        unsafe {
            G2Affine::from_xy_unchecked(
                Fp2::new(self.x.c0.to_intrinsic(), self.x.c1.to_intrinsic()),
                Fp2::new(self.y.c0.to_intrinsic(), self.y.c1.to_intrinsic()),
            )
        }
    }
}
